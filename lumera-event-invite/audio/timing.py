"""Lays the voiceover out on the timeline and finds when each key word is spoken.

Reads vo_lines.json and the rendered lines in vo/, places each line a short
breath after the one before, and uses Whisper word timestamps to find every
"mark" (the words the picture cuts and slams on). Writes:

    vo_lines.json   each line's start time "t"
    vo_words.json   every word Whisper heard, for reference
    ../timing.js    window.TIMING = {lines, W, dur}; index.html builds the edit from it

    python timing.py        (after make_vo.py; needs faster-whisper)

A mark is [key, "word|alternative|..."]. Marks are found in order within their
line, with words compared in lower case without punctuation ("7:25" -> "725").
A third element [other_key, offset] is used when Whisper writes the words in
a way none of the alternatives match.
"""
import json
import os
import re
import sys

import numpy as np
import soundfile as sf
from faster_whisper import WhisperModel
from scipy import signal

HERE = os.path.dirname(os.path.abspath(__file__))
GAP = .3          # breath between lines unless a line sets its own "gap"
TAIL = 1.5        # hold on the end card after the last word
LEAD = .02        # a cut lands a frame or so before the word itself

norm = lambda w: re.sub(r'[^a-z0-9]', '', w.lower())


def main():
    lines = json.load(open(os.path.join(HERE, 'vo_lines.json')))
    model = WhisperModel('small.en', device='cpu', compute_type='int8')
    t, W, out, timing, missing = 0., {}, [], {}, []
    for ln in lines:
        a, sr = sf.read(os.path.join(HERE, 'vo', ln['id'] + '.wav'))
        if a.ndim > 1:
            a = a.mean(1)
        d = len(a) / sr
        t += ln.get('gap', GAP)
        ln['t'] = round(t, 3)
        x = signal.resample_poly(a, 16000, sr).astype(np.float32)
        segs, _ = model.transcribe(x, beam_size=5, word_timestamps=True, initial_prompt='Lumera, Kahoot, Jafar Center, Dubai College')
        words = [(w.word.strip(), w.start) for s in segs for w in s.words]
        out.append({'id': ln['id'], 'words': [{'w': w, 's': round(t + s, 3)} for w, s in words]})
        print(f"{ln['id']} {t:6.2f}s +{d:4.2f}s  {' '.join(w for w, _ in words)}")
        i = 0
        for mk in ln.get('marks', []):
            key, alts = mk[0], set(mk[1].split('|'))
            j = next((j for j in range(i, len(words)) if norm(words[j][0]) in alts), None)
            if j is None:
                if len(mk) > 2 and mk[2][0] in W:
                    W[key] = round(W[mk[2][0]] + mk[2][1], 3)
                    print(f'   {key}: not heard, set {mk[2][1]:+.2f}s from {mk[2][0]}')
                else:
                    missing.append(f"{ln['id']}:{key}")
                continue
            W[key] = round(t + words[j][1] - LEAD, 3)
            i = j + 1
        timing[ln['id']] = {'t': ln['t'], 'd': round(d, 3)}
        t += d
    if missing:
        sys.exit('marks not found: ' + ', '.join(missing))
    dur = round(t + TAIL, 2)
    with open(os.path.join(HERE, 'vo_lines.json'), 'w') as f:
        f.write('[\n' + ',\n'.join(' ' + json.dumps(ln, ensure_ascii=False) for ln in lines) + '\n]\n')
    json.dump(out, open(os.path.join(HERE, 'vo_words.json'), 'w'), indent=1)
    with open(os.path.join(os.path.dirname(HERE), 'timing.js'), 'w') as f:
        f.write('// generated by audio/timing.py from the voiceover; do not edit by hand\n')
        f.write('window.TIMING = ' + json.dumps({'lines': timing, 'W': W, 'dur': dur}) + ';\n')
    print(f'{len(W)} marks, {dur:.2f}s -> timing.js')


if __name__ == '__main__':
    main()
