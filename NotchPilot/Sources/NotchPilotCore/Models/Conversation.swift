import Foundation

/// A document the user explicitly attached to a message.
public struct DocumentAttachment: Codable, Equatable, Sendable, Identifiable {
    public var id: UUID
    public var fileName: String
    /// Extracted text (may be truncated; see `totalCharacters`).
    public var text: String
    public var totalCharacters: Int

    public init(id: UUID = UUID(), fileName: String, text: String, totalCharacters: Int? = nil) {
        self.id = id
        self.fileName = fileName
        self.text = text
        self.totalCharacters = totalCharacters ?? text.count
    }

    public var isTruncated: Bool { text.count < totalCharacters }
}

public struct ToolUseBlock: Codable, Equatable, Sendable {
    public var id: String
    public var name: String
    public var input: JSONValue

    public init(id: String, name: String, input: JSONValue) {
        self.id = id
        self.name = name
        self.input = input
    }
}

public struct ToolResultBlock: Codable, Equatable, Sendable {
    public var toolUseID: String
    public var toolName: String
    public var content: String
    public var isError: Bool

    public init(toolUseID: String, toolName: String, content: String, isError: Bool) {
        self.toolUseID = toolUseID
        self.toolName = toolName
        self.content = content
        self.isError = isError
    }
}

/// Provider-neutral content. Used for display and for converting history when
/// a conversation is continued with a different provider.
public enum ContentBlock: Codable, Equatable, Sendable {
    /// Visible text written by the user or the assistant.
    case text(String)
    /// Per-turn context generated by the app (date, preferences, memories).
    /// Sent to the model, hidden from the conversation view.
    case context(String)
    case attachment(DocumentAttachment)
    case toolUse(ToolUseBlock)
    case toolResult(ToolResultBlock)
    /// Short progress note the model wrote between tool calls.
    case progress(String)

    public var text: String? {
        if case .text(let t) = self { return t }
        return nil
    }
}

/// Provider-native content for exact replay. Thinking blocks (Anthropic) and
/// reasoning items (OpenAI) must be sent back unchanged, so assistant turns keep
/// the raw blocks they arrived with.
public struct NativeContent: Codable, Equatable, Sendable {
    public enum Format: String, Codable, Sendable {
        case anthropicMessages
        case openAIResponses
        case openAIChat
    }

    public var format: Format
    public var items: [JSONValue]

    public init(format: Format, items: [JSONValue]) {
        self.format = format
        self.items = items
    }
}

public enum TurnRole: String, Codable, Sendable {
    case user
    case assistant
}

public enum TurnStatus: String, Codable, Sendable {
    case complete
    /// Stopped by the user or by a limit before the model finished.
    case interrupted
    /// The provider's safety system declined the request.
    case refused
    case failed
}

public struct ConversationTurn: Codable, Equatable, Sendable, Identifiable {
    public var id: UUID
    public var role: TurnRole
    public var blocks: [ContentBlock]
    public var native: NativeContent?
    public var createdAt: Date
    public var status: TurnStatus
    /// Model that produced an assistant turn (may differ from the requested one after a fallback).
    public var servedModel: String?
    /// Turns kept for display only and never sent to the model again
    /// (for example a partial answer that was declined).
    public var excludedFromContext: Bool

    public init(
        id: UUID = UUID(), role: TurnRole, blocks: [ContentBlock], native: NativeContent? = nil,
        createdAt: Date, status: TurnStatus = .complete, servedModel: String? = nil, excludedFromContext: Bool = false
    ) {
        self.id = id
        self.role = role
        self.blocks = blocks
        self.native = native
        self.createdAt = createdAt
        self.status = status
        self.servedModel = servedModel
        self.excludedFromContext = excludedFromContext
    }

    public var visibleText: String {
        blocks.compactMap(\.text).joined(separator: "\n\n")
    }

    public var toolUses: [ToolUseBlock] {
        blocks.compactMap { if case .toolUse(let use) = $0 { return use } else { return nil } }
    }

    public var toolResults: [ToolResultBlock] {
        blocks.compactMap { if case .toolResult(let result) = $0 { return result } else { return nil } }
    }

    /// True for user turns that only carry tool results (not typed by the user).
    public var isToolResultTurn: Bool {
        role == .user && !blocks.isEmpty && blocks.allSatisfy {
            if case .toolResult = $0 { return true }
            return false
        }
    }
}

public struct Conversation: Codable, Equatable, Sendable, Identifiable {
    public var id: UUID
    public var title: String
    public var createdAt: Date
    public var updatedAt: Date
    public var turns: [ConversationTurn]
    public var actions: [ActionRecord]
    public var lastProvider: ProviderKind?
    public var lastModel: String?

    public init(id: UUID = UUID(), title: String = "New conversation", createdAt: Date, turns: [ConversationTurn] = [], actions: [ActionRecord] = []) {
        self.id = id
        self.title = title
        self.createdAt = createdAt
        self.updatedAt = createdAt
        self.turns = turns
        self.actions = actions
    }

    /// Turns sent to the model.
    public var contextTurns: [ConversationTurn] {
        turns.filter { !$0.excludedFromContext }
    }

    public var isEmpty: Bool { turns.isEmpty }

    public var searchableText: String {
        ([title] + turns.map(\.visibleText)).joined(separator: "\n")
    }
}

/// Lightweight listing entry so the history view does not load every transcript.
public struct ConversationSummary: Codable, Equatable, Sendable, Identifiable {
    public var id: UUID
    public var title: String
    public var createdAt: Date
    public var updatedAt: Date
    public var preview: String
    public var turnCount: Int

    public init(_ conversation: Conversation) {
        id = conversation.id
        title = conversation.title
        createdAt = conversation.createdAt
        updatedAt = conversation.updatedAt
        let lastText = conversation.turns.last(where: { !$0.visibleText.isEmpty })?.visibleText ?? ""
        preview = TextUtilities.preview(lastText, limit: 90)
        turnCount = conversation.turns.count
    }
}
