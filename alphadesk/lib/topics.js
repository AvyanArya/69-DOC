/** Label for how hot a topic is right now (growth = blend of 1W/1M/3M returns). */
export function heatOf(rank, total, growth, ret63) {
  if (rank < Math.ceil(total * 0.2) && growth > 0) return { label: 'Hot', tone: 'up' };
  if (growth > 0) return { label: 'Warming', tone: 'up' };
  if (ret63 > 0) return { label: 'Cooling', tone: 'neutral' };
  return { label: 'Cold', tone: 'down' };
}
